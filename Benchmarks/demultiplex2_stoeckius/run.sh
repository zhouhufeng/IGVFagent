#!/usr/bin/env bash
# deMULTIplex2 (Zhu, Conrad & Gartner, Genome Biol 2024) — reproduction.
#   1. Stoeckius 2018 PBMC HTO matrix bundled with deMULTIplex2 -> multiseq (behaviour checks)
#   2. Table S3 lung cell line + BAL1-3 (Oshlack/hashtag-demux-paper, genetic truth)
#      -> demultiplex2-benchmark (port of R/benchmarking.R)
#   3. Table S3 Gaublomme (regevlab/demuxem docker inputs, demuxlet truth), if the image is available
#   4. Fig. 2B simulations 1-5 (authors' simulateTags, needs R), if R is available
#   5. With REF=1: the authors' R deMULTIplex2 on the same inputs (reference for verify-port)
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
cd "$ROOT"
LABEL="demultiplex2_stoeckius"
D="Benchmarks/_data/$LABEL"
Z="Data/zhu2024"
if .venv/bin/python -c "" 2>/dev/null; then IGVF=.venv/bin/igvfagent; PY=.venv/bin/python
else IGVF=igvfagent; PY="$(dirname "$(command -v igvfagent)")/python"; fi
R_BIN="${R_BIN:-/n/sw/helmod-rocky8/apps/Core/R/4.4.1-fasrc01/bin}"
PKG_COMMIT=de48333b89f60447bc037237f6cb45985ffb33f4
OSHLACK_COMMIT=3be94bbda8861972d2e8f235129da2d95af52857
mkdir -p "$D" "$Z/work/local"

# 1) Stoeckius 8-donor PBMC HTO matrix bundled with deMULTIplex2 (public).
$PY -c "import pyreadr" 2>/dev/null || $PY -m pip install -q pyreadr
if [ ! -f "$D/stoeckius_pbmc.RData" ]; then
  curl -sL -o "$D/stoeckius_pbmc.RData" \
    "https://raw.githubusercontent.com/Gartner-Lab/deMULTIplex2/$PKG_COMMIT/data/stoeckius_pbmc.RData"
fi
$PY "$HERE/prep_input.py"
$IGVF multiseq demultiplex --input "$D/stoeckius_tags.csv" --label "$LABEL"
$PY "$HERE/make_figures.py"

# 2) Lung cell line + BAL batches 1-3 against genetic (vireo) donor truth.
if [ ! -d "$Z/oshlack/.git" ]; then
  git clone -q https://github.com/Oshlack/hashtag-demux-paper.git "$Z/oshlack"
fi
git -C "$Z/oshlack" checkout -q "$OSHLACK_COMMIT"
O="$Z/work/oshlack"
$PY "$HERE/ref/prep_oshlack.py" --repo "$Z/oshlack" --out "$O"
for ds in lung_cellline bal_batch1 bal_batch2 bal_batch3; do
  caps=$($PY -c "import json;print(' '.join('$O/'+c for c in json.load(open('$O/oshlack_manifest.json'))['$ds']['captures']))")
  $IGVF demultiplex2-benchmark --tags $caps --truth "$O/${ds}_truth.csv" \
      --tag-mapping "$O/${ds}_tag_mapping.json" --max-cell-fit 1000 \
      --label "zhu2024_ts3_$ds" --outdir "Docs/MultiSeq/zhu2024_ts3_$ds"
done

# 3) Gaublomme nuclei hashing: inputs live in the regevlab/demuxem docker image.
G="$Z/gaublomme"
if [ ! -d "$G/inputs/experiment1_human_st_raw_GRCh38_premrna" ] && command -v singularity >/dev/null; then
  mkdir -p "$G/inputs"
  [ -f "$G/demuxem.sif" ] || singularity pull "$G/demuxem.sif" docker://regevlab/demuxem:latest
  singularity exec -B "$ROOT/$G/inputs:/out" "$G/demuxem.sif" sh -c \
    'cp -r /software/inputs/experiment1_human_st_ADT.csv /software/inputs/experiment1_demuxlet.best /software/inputs/experiment1_human_st_raw_GRCh38_premrna /out/'
fi
if [ -d "$G/inputs/experiment1_human_st_raw_GRCh38_premrna" ]; then
  GW="$Z/work/gaublomme"
  $PY "$HERE/ref/prep_gaublomme.py" "$G/inputs" "$GW"
  $IGVF demultiplex2-benchmark --tags "$GW/gaublomme_c1_tags.csv" --truth "$GW/gaublomme_truth.csv" \
      --tag-mapping "$GW/gaublomme_tag_mapping.json" --max-cell-fit 5000 --max-quantile-fit 0.9 \
      --label zhu2024_ts3_gaublomme --outdir Docs/MultiSeq/zhu2024_ts3_gaublomme
fi

# 4) Fig. 2B simulations (generated by the authors' simulateTags in R).
if [ ! -d "$Z/pkg_repo/.git" ]; then
  git clone -q https://github.com/Gartner-Lab/deMULTIplex2.git "$Z/pkg_repo"
fi
git -C "$Z/pkg_repo" checkout -q "$PKG_COMMIT"
S="$Z/work/sim"
if [ -x "$R_BIN/Rscript" ]; then
  [ -f "$S/sim_manifest.json" ] || "$R_BIN/Rscript" "$HERE/ref/make_simulations.R" "$Z/pkg_repo" "$S"
fi
if [ -f "$S/sim_manifest.json" ]; then
  for s in sim1 sim2 sim3 sim4 sim5; do
    $IGVF demultiplex2-benchmark --tags "$S/${s}_c1_tags.csv" --truth "$S/${s}_truth.csv" \
        --tag-mapping "$S/${s}_tag_mapping.json" --max-cell-fit 5000 \
        --label "zhu2024_fig2b_$s" --outdir "Docs/MultiSeq/zhu2024_fig2b_$s"
  done
fi

# 5) Optional: the authors' R code on the same inputs (reference outputs for verify-port).
if [ "${REF:-0}" = 1 ] && [ -x "$R_BIN/Rscript" ]; then
  L="$Z/work/local"
  "$R_BIN/Rscript" "$HERE/ref/run_demux2_ref.R" "$Z/pkg_repo" "$Z/work/stoeckius_pbmc_tags.csv" "$L/ref_stoeckius_pbmc_nosub" 1e9 30
  for ds in lung_cellline bal_batch1 bal_batch2 bal_batch3; do
    "$R_BIN/Rscript" "$HERE/ref/run_bench_ref.R" "$Z/pkg_repo" "$O" "$O/oshlack_manifest.json" "$ds" "$L/ref_${ds}_nosub" 1e9
  done
  for s in sim1 sim2 sim3 sim4 sim5; do
    "$R_BIN/Rscript" "$HERE/ref/run_bench_ref.R" "$Z/pkg_repo" "$S" "$S/sim_manifest.json" "$s" "$L/ref_${s}_nosub" 1e9
  done
  [ -d "$Z/work/gaublomme" ] && "$R_BIN/Rscript" "$HERE/ref/run_bench_ref.R" "$Z/pkg_repo" "$Z/work/gaublomme" \
      "$Z/work/gaublomme/gaublomme_manifest.json" gaublomme "$L/ref_gaublomme_nosub" 1e9 0.9
fi

echo ""
echo "== deMULTIplex2 benchmark complete =="
echo "Score with: igvfagent bench score --paper-id $LABEL"
